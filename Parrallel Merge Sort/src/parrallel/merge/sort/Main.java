    private void runButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_runButtonActionPerformed
        if (currentArray == null) {
            System.out.println("Please reset array first!");
            return;
        }

        int delay = (Integer) speed.getValue(); 
        int algorithmIndex = algorithmsSelector.getSelectedIndex();

        runButton.setEnabled(false);
        resetArrayButton.setEnabled(false);

        Thread animation = new Thread() {
            @Override
            public void run() {

                ArrayVisualizer viz = (ArrayVisualizer) visualizerPanel;

                switch (algorithmIndex) {
                    case 0 ->                         {
                            sortAlgorithm sorter = new MergeSort(viz, delay);
                            sorter.sort(currentArray);
                        }
                    case 1 ->                         {
                            sortAlgorithm sorter = new ParallelMergeSort(viz, delay);
                            sorter.sort(currentArray);
                        }
                    case 2 -> {
                        java.util.Arrays.sort(currentArray);
                        viz.repaint();
                    }
                    default -> {
                    }
                }

                runButton.setEnabled(true);
                resetArrayButton.setEnabled(true);

            }
        };

        animation.start();
    }//GEN-LAST:event_runButtonActionPerformed

    private void resetArrayButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_resetArrayButtonActionPerformed
        
        int s = (Integer) size.getValue(); 

        int typeIndex = ArrayTypeSelector.getSelectedIndex();

        switch (typeIndex) {
            case 0 -> // Random
                currentArray = SortBenchmark.generateRandomArray(s);
            case 1 -> // Sorted
                currentArray = SortBenchmark.generateReverseSortedArray(s);
            case 2 -> // Reverse
                currentArray = SortBenchmark.generateSortedArray(s);
        }
        
        ArrayVisualizer v = (ArrayVisualizer) visualizerPanel;
        v.setArray(currentArray);
    }//GEN-LAST:event_resetArrayButtonActionPerformed

    private void runBenchmarkActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_runBenchmarkActionPerformed
        benchmarkOutput.setText("");
        final javax.swing.JButton btn = (javax.swing.JButton) evt.getSource();
        btn.setEnabled(false);
        
        benchmarkOutput.append("Starting Benchmark... Please wait.\n");

        Thread worker = new Thread() {

            @Override
            public void run() {
                benchmarkOutput.append("=== SORTING ALGORITHM BENCHMARK ===\n\n");

                int[] sizes = {10_000, 100_000, 1_000_000};
                int runs = 5;

                sortAlgorithm sequential = new MergeSort();
                sortAlgorithm parallel = new ParallelMergeSort();

                for (int i = 0; i < sizes.length; i++) {
                    int size = sizes[i];

                    benchmarkOutput.append("===================================\n");
                    benchmarkOutput.append("Array Size: " + size + "\n");
                    benchmarkOutput.append("===================================\n");

                    // --- RANDOM ARRAY ---
                    benchmarkOutput.append("\n--- RANDOM ARRAY ---\n\n");
                    int[] randomArray = generateRandomArray(size);

                    SortBenchmark.BenchmarkResult seqResultRandom = 
                        SortBenchmark.runBenchmarkWithComparisons(sequential, randomArray, runs);
                    benchmarkOutput.append("Sequential MergeSort:\n");
                    benchmarkOutput.append("  Time: " + toMilliseconds(seqResultRandom.time) + " ms\n");
                    benchmarkOutput.append("  Comparisons: " + seqResultRandom.comparisons + "\n\n");
                    

                    SortBenchmark.BenchmarkResult parResultRandom = 
                        SortBenchmark.runBenchmarkWithComparisons(parallel, randomArray, runs);
                    benchmarkOutput.append("Parallel MergeSort:\n");
                    benchmarkOutput.append("  Time: " + toMilliseconds(parResultRandom.time) + " ms\n");
                    benchmarkOutput.append("  Comparisons: " + parResultRandom.comparisons + "\n\n");
                    
                    
                    double speedup = (double) seqResultRandom.time / parResultRandom.time;
                    benchmarkOutput.append(String.format("  Speedup: %.2fx\n\n", speedup));

                    
                    long builtinTimeRandom = benchmarkBuiltinSort(randomArray, runs);
                    benchmarkOutput.append("Arrays.sort:\n");
                    benchmarkOutput.append("  Time: " + toMilliseconds(builtinTimeRandom) + " ms\n");
                    benchmarkOutput.append("  Comparisons: N/A (built-in)\n\n");

                    // --- REVERSE SORTED ARRAY ---
                    benchmarkOutput.append("\n--- REVERSE SORTED ARRAY ---\n\n");
                    int[] reverseArray = generateReverseSortedArray(size);

                    SortBenchmark.BenchmarkResult seqResultReverse = 
                        SortBenchmark.runBenchmarkWithComparisons(sequential, reverseArray, runs);
                    benchmarkOutput.append("Sequential MergeSort:\n");
                    benchmarkOutput.append("  Time: " + toMilliseconds(seqResultReverse.time) + " ms\n");
                    benchmarkOutput.append("  Comparisons: " + seqResultReverse.comparisons + "\n\n");

                    SortBenchmark.BenchmarkResult parResultReverse = 
                        SortBenchmark.runBenchmarkWithComparisons(parallel, reverseArray, runs);
                    benchmarkOutput.append("Parallel MergeSort:\n");
                    benchmarkOutput.append("  Time: " + toMilliseconds(parResultReverse.time) + " ms\n");
                    benchmarkOutput.append("  Comparisons: " + parResultReverse.comparisons + "\n\n");
                    
                    
                    speedup = (double) seqResultReverse.time / parResultReverse.time;
                    benchmarkOutput.append(String.format("  Speedup: %.2fx\n\n", speedup));
                    

                    long builtinTimeReverse = benchmarkBuiltinSort(reverseArray, runs);
                    benchmarkOutput.append("Arrays.sort:\n");
                    benchmarkOutput.append("  Time: " + toMilliseconds(builtinTimeReverse) + " ms\n");
                    benchmarkOutput.append("  Comparisons: N/A (built-in)\n\n");

                    // --- SORTED ARRAY ---
                    benchmarkOutput.append("\n--- SORTED ARRAY ---\n\n");
                    int[] sortedArray = generateSortedArray(size);

                    SortBenchmark.BenchmarkResult seqResultSorted = 
                        SortBenchmark.runBenchmarkWithComparisons(sequential, sortedArray, runs);
                    benchmarkOutput.append("Sequential MergeSort:\n");
                    benchmarkOutput.append("  Time: " + toMilliseconds(seqResultSorted.time) + " ms\n");
                    benchmarkOutput.append("  Comparisons: " + seqResultSorted.comparisons + "\n\n");

                    SortBenchmark.BenchmarkResult parResultSorted = 
                        SortBenchmark.runBenchmarkWithComparisons(parallel, sortedArray, runs);
                    benchmarkOutput.append("Parallel MergeSort:\n");
                    benchmarkOutput.append("  Time: " + toMilliseconds(parResultSorted.time) + " ms\n");
                    benchmarkOutput.append("  Comparisons: " + parResultSorted.comparisons + "\n\n");
                    
                    
                    speedup = (double) seqResultSorted.time / parResultSorted.time;
                    benchmarkOutput.append(String.format("  Speedup: %.2fx\n\n", speedup));
                    

                    long builtinTimeSorted = benchmarkBuiltinSort(sortedArray, runs);
                    benchmarkOutput.append("Arrays.sort:\n");
                    benchmarkOutput.append("  Time: " + toMilliseconds(builtinTimeSorted) + " ms\n");
                    benchmarkOutput.append("  Comparisons: N/A (built-in)\n\n");

                    benchmarkOutput.append("\n");
                    benchmarkOutput.setCaretPosition(benchmarkOutput.getDocument().getLength());
                }

                benchmarkOutput.append("===================================\n");
                benchmarkOutput.append("BENCHMARK COMPLETE\n");
                benchmarkOutput.append("===================================\n");

                btn.setEnabled(true);
            }
        };

        worker.start();
    
    }//GEN-LAST:event_runBenchmarkActionPerformed

